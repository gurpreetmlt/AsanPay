/**
 * Branded report exports (PDF via the browser's print dialog, Excel as a styled .xls sheet).
 * Shared by admin registers so every CA / audit export carries the same letterhead.
 */

export const COMPANY_LETTERHEAD = {
  legalName: "ASANPAY INNOVATION PRIVATE LIMITED",
  addressLines: ["H.No 103, Main Bazar Road", "Street Number 10, Birla Road", "Malout, Punjab 152107"],
  website: "asanpay.in",
};

export type CellTone = "credit" | "debit" | "muted" | "approved" | "requested" | "rejected";

export interface ReportCell {
  text: string;
  /** Optional second line in smaller muted type (PDF only; Excel joins with " · "). */
  sub?: string;
  tone?: CellTone;
  align?: "left" | "right" | "center";
  mono?: boolean;
}

export interface BrandedReport {
  title: string;
  fileName: string;
  /** Right-hand header facts, e.g. Period, Generated on, Generated by. */
  meta: { label: string; value: string }[];
  /** Highlighted summary tiles under the header. */
  summary: { label: string; value: string; tone?: "credit" | "debit" | "neutral" }[];
  columns: { label: string; align?: "left" | "right" | "center"; width?: string }[];
  rows: ReportCell[][];
  footerNote?: string;
}

function esc(v: string) {
  return v.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

const TONE_COLOR: Record<CellTone, string> = {
  credit: "#15803D",
  debit: "#B91C1C",
  muted: "#64748B",
  approved: "#15803D",
  requested: "#B45309",
  rejected: "#B91C1C",
};

const STATUS_BG: Partial<Record<CellTone, string>> = {
  approved: "#DCFCE7",
  requested: "#FEF3C7",
  rejected: "#FEE2E2",
};

function assetUrl(path: string) {
  return `${window.location.origin}${path}`;
}

/** Opens a print-ready letterhead report; "Save as PDF" in the print dialog produces the file. */
export function openBrandedPdf(report: BrandedReport): boolean {
  const win = window.open("", "_blank");
  if (!win) return false;

  const logo = assetUrl("/brand/asanpay-logo-dark.png");
  const icon = assetUrl("/brand/AsanPay-Light-Icon.png");

  const cell = (c: ReportCell) => {
    const isStatus = c.tone === "approved" || c.tone === "requested" || c.tone === "rejected";
    const color = c.tone ? TONE_COLOR[c.tone] : "#0F172A";
    const main = isStatus
      ? `<span class="pill" style="color:${color};background:${STATUS_BG[c.tone!]}">${esc(c.text)}</span>`
      : `<span style="color:${color}">${esc(c.text)}</span>`;
    const sub = c.sub ? `<div class="sub">${esc(c.sub)}</div>` : "";
    const cls = [c.mono ? "mono" : "", c.align ? `a-${c.align}` : ""].filter(Boolean).join(" ");
    return `<td class="${cls}">${main}${sub}</td>`;
  };

  const summaryHtml = report.summary
    .map((s) => {
      const color = s.tone === "credit" ? "#15803D" : s.tone === "debit" ? "#B91C1C" : "#0B2A6F";
      return `<div class="tile"><div class="tile-l">${esc(
        s.label,
      )}</div><div class="tile-v" style="color:${color}">${esc(s.value)}</div></div>`;
    })
    .join("");

  win.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(report.fileName)}</title>
<style>
@page { size: A4 landscape; margin: 12mm 10mm 14mm; }
* { box-sizing: border-box; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
body { font-family: "Helvetica Neue", Arial, sans-serif; color: #0F172A; margin: 0; font-size: 10px; }
.watermark { position: fixed; top: 50%; left: 50%; width: 360px; height: 360px; transform: translate(-50%, -42%);
  opacity: 0.06; z-index: 0; pointer-events: none; }
.page { position: relative; z-index: 1; }
.head { display: flex; justify-content: space-between; align-items: flex-start; gap: 24px;
  padding-bottom: 10px; border-bottom: 3px solid #1D4ED8; }
.brand img { height: 54px; display: block; }
.company { margin-top: 6px; font-size: 9.5px; color: #334155; line-height: 1.45; }
.company b { color: #0B2A6F; font-size: 10.5px; letter-spacing: .3px; }
.doc { text-align: right; }
.doc h1 { margin: 0 0 6px; font-size: 18px; letter-spacing: .5px; color: #0B2A6F; text-transform: uppercase; }
.meta { border-collapse: collapse; margin-left: auto; font-size: 9.5px; }
.meta td { padding: 1.5px 0 1.5px 10px; border: 0; }
.meta td:first-child { color: #64748B; text-align: right; }
.meta td:last-child { font-weight: 700; color: #0F172A; text-align: left; }
.stripe { height: 3px; background: linear-gradient(90deg, #16A34A, #F97316); margin-bottom: 12px; }
.tiles { display: flex; gap: 8px; margin-bottom: 12px; }
.tile { flex: 1; border: 1px solid #DBEAFE; background: rgba(239,246,255,.85); border-radius: 8px; padding: 7px 10px; }
.tile-l { font-size: 8.5px; color: #64748B; text-transform: uppercase; letter-spacing: .4px; font-weight: 700; }
.tile-v { font-size: 14px; font-weight: 800; margin-top: 2px; }
table.data { width: 100%; border-collapse: collapse; }
table.data thead th { background: #0B2A6F; color: #fff; font-size: 8.5px; text-transform: uppercase; letter-spacing: .3px;
  padding: 6px 5px; text-align: left; border: 1px solid #0B2A6F; }
table.data td { padding: 5px; border-bottom: 1px solid #E2E8F0; vertical-align: top; font-size: 9.5px; background: rgba(255,255,255,.7); }
table.data tbody tr:nth-child(even) td { background: rgba(248,250,252,.8); }
table.data tr { page-break-inside: avoid; }
thead { display: table-header-group; }
.sub { color: #64748B; font-size: 8.5px; margin-top: 1px; }
.mono { font-family: "SF Mono", Menlo, Consolas, monospace; font-size: 9px; }
.a-right { text-align: right; } .a-center { text-align: center; }
.pill { display: inline-block; padding: 1px 7px; border-radius: 999px; font-weight: 700; font-size: 8.5px; text-transform: capitalize; }
.foot { margin-top: 14px; padding-top: 8px; border-top: 1px dashed #CBD5E1; display: flex; justify-content: space-between;
  color: #64748B; font-size: 8.5px; }
.end { text-align: center; margin-top: 10px; font-weight: 700; color: #334155; letter-spacing: 1px; font-size: 9px; }
</style></head><body>
<img class="watermark" src="${icon}" alt="" />
<div class="page">
  <div class="head">
    <div class="brand">
      <img src="${logo}" alt="AsanPay" />
      <div class="company"><b>${esc(COMPANY_LETTERHEAD.legalName)}</b><br/>${COMPANY_LETTERHEAD.addressLines
    .map(esc)
    .join("<br/>")}</div>
    </div>
    <div class="doc">
      <h1>${esc(report.title)}</h1>
      <table class="meta">${report.meta
        .map((m) => `<tr><td>${esc(m.label)}</td><td>${esc(m.value)}</td></tr>`)
        .join("")}</table>
    </div>
  </div>
  <div class="stripe"></div>
  <div class="tiles">${summaryHtml}</div>
  <table class="data">
    <thead><tr>${report.columns
      .map(
        (c) =>
          `<th style="${c.width ? `width:${c.width};` : ""}${c.align ? `text-align:${c.align};` : ""}">${esc(
            c.label,
          )}</th>`,
      )
      .join("")}</tr></thead>
    <tbody>${
      report.rows.length
        ? report.rows.map((r) => `<tr>${r.map(cell).join("")}</tr>`).join("")
        : `<tr><td colspan="${report.columns.length}" class="a-center" style="padding:18px;color:#64748B">No entries for this period</td></tr>`
    }</tbody>
  </table>
  <div class="end">*** END OF REPORT ***</div>
  <div class="foot">
    <span>${esc(report.footerNote ?? "System-generated report from AsanPay Admin. Amounts in INR.")}</span>
    <span>${esc(COMPANY_LETTERHEAD.website)}</span>
  </div>
</div>
<script>
  window.onload = function () { setTimeout(function () { window.print(); }, 250); };
</script>
</body></html>`);
  win.document.close();
  return true;
}

/** Styled Excel workbook (.xls, HTML spreadsheet) with letterhead rows above the data table. */
export function downloadBrandedExcel(report: BrandedReport) {
  const span = report.columns.length;
  const logo = assetUrl("/brand/asanpay-logo-dark.png");
  const td = (c: ReportCell) => {
    const color = c.tone ? TONE_COLOR[c.tone] : "#0F172A";
    const bg = c.tone && STATUS_BG[c.tone] ? `background:${STATUS_BG[c.tone]};` : "";
    const text = c.sub ? `${c.text} · ${c.sub}` : c.text;
    const fmt = c.mono ? "mso-number-format:'\\@';" : "";
    return `<td style="border:1px solid #CBD5E1;color:${color};${bg}${fmt}text-align:${
      c.align ?? "left"
    };vertical-align:top">${esc(text)}</td>`;
  };

  const html = `<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
<head><meta charset="utf-8"><!--[if gte mso 9]><xml><x:ExcelWorkbook><x:ExcelWorksheets><x:ExcelWorksheet>
<x:Name>${esc(report.title.slice(0, 31))}</x:Name><x:WorksheetOptions><x:DisplayGridlines/></x:WorksheetOptions>
</x:ExcelWorksheet></x:ExcelWorksheets></x:ExcelWorkbook></xml><![endif]--></head>
<body style="font-family:Arial">
<table style="border-collapse:collapse;font-family:Arial;font-size:10pt">
<tr style="height:60px"><td colspan="${Math.min(
    4,
    span,
  )}" style="vertical-align:middle"><img src="${logo}" width="170" height="58" alt="AsanPay"/></td>
<td colspan="${Math.max(
    1,
    span - 4,
  )}" style="text-align:right;vertical-align:middle;font-size:16pt;font-weight:bold;color:#0B2A6F">${esc(
    report.title.toUpperCase(),
  )}</td></tr>
<tr><td colspan="${span}" style="font-weight:bold;color:#0B2A6F;font-size:11pt">${esc(
    COMPANY_LETTERHEAD.legalName,
  )}</td></tr>
<tr><td colspan="${span}" style="color:#475569">${esc(COMPANY_LETTERHEAD.addressLines.join(", "))}</td></tr>
${report.meta
  .map(
    (m) =>
      `<tr><td colspan="2" style="color:#64748B">${esc(m.label)}</td><td colspan="${Math.max(
        1,
        span - 2,
      )}" style="font-weight:bold">${esc(m.value)}</td></tr>`,
  )
  .join("")}
<tr><td colspan="${span}" style="border-bottom:2px solid #1D4ED8"></td></tr>
<tr>${report.summary
    .map((s) => {
      const color = s.tone === "credit" ? "#15803D" : s.tone === "debit" ? "#B91C1C" : "#0B2A6F";
      return `<td colspan="2" style="background:#EFF6FF;border:1px solid #BFDBFE;padding:4px"><span style="color:#64748B;font-size:8pt">${esc(
        s.label.toUpperCase(),
      )}</span><br/><b style="color:${color};font-size:12pt">${esc(s.value)}</b></td>`;
    })
    .join("")}</tr>
<tr><td colspan="${span}"></td></tr>
<tr>${report.columns
    .map(
      (c) =>
        `<th style="background:#0B2A6F;color:#FFFFFF;border:1px solid #0B2A6F;font-weight:bold;text-align:${
          c.align ?? "left"
        };padding:4px">${esc(c.label)}</th>`,
    )
    .join("")}</tr>
${report.rows.map((r) => `<tr>${r.map(td).join("")}</tr>`).join("")}
<tr><td colspan="${span}"></td></tr>
<tr><td colspan="${span}" style="color:#64748B;font-size:8pt">${esc(
    report.footerNote ?? "System-generated report from AsanPay Admin. Amounts in INR.",
  )}</td></tr>
</table></body></html>`;

  const blob = new Blob([`\uFEFF${html}`], { type: "application/vnd.ms-excel;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${report.fileName}.xls`;
  a.click();
  URL.revokeObjectURL(url);
}
