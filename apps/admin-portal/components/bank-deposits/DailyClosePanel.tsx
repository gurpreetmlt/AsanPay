"use client";

import { useCallback, useEffect, useState } from "react";
import Link from "next/link";
import { toast } from "react-hot-toast";
import { CheckCircle2, Circle, Download, FileSpreadsheet, FileText, Lock, Unlock } from "lucide-react";
import api, { fetchApi } from "@/lib/api";
import { B } from "@/lib/brand";
import { downloadBrandedExcel, openBrandedPdf, type BrandedReport } from "@/lib/brandedExport";
import { useAuthStore } from "@/lib/store";

interface DailyCloseStep {
  id: string;
  title: string;
  detail: string;
  done: boolean;
  blocking: boolean;
  count: number;
  href: string | null;
}

interface DailyCloseBank {
  id: string;
  bankName: string;
  last4: string;
  uploaded: boolean;
}

interface BankDayBalance {
  bankAccountId: string;
  bankName: string;
  last4: string;
  uploaded: boolean;
  locked: boolean;
  lockedAt: string | null;
  statementOpening: string | null;
  statementClosing: string | null;
  booksOpening: string;
  booksClosing: string;
  drift: string | null;
  status: "ok" | "drift" | "missing_statement" | "locked";
}

interface DailyCloseStatus {
  date: string;
  closed: boolean;
  closedAt: string | null;
  closedByName: string | null;
  note: string | null;
  canClose: boolean;
  banks: DailyCloseBank[];
  balances: BankDayBalance[];
  steps: DailyCloseStep[];
}

interface DailySummary {
  date: string;
  unmatchedCredits: number;
  pendingFundRequests: number;
  pendingBankEntries: number;
  statementCredits: string;
  statementDebits: string;
  creditedFundRequests: string;
  provider: {
    floatIn: string;
    floatOut: string;
    fees: string;
    walletImpact: string;
    netFloat: string;
    journalCount: number;
  };
  dailyClose: { closed: boolean; canClose: boolean; closedByName: string | null };
  banks: { bankName: string; last4: string; uploaded: boolean }[];
  text: string;
  lines: { label: string; value: string }[];
}

function istToday(): string {
  return new Date(Date.now() + 5.5 * 3600 * 1000).toISOString().slice(0, 10);
}

function errMessage(err: unknown, fallback: string) {
  const ax = err as { response?: { data?: { message?: string } }; message?: string };
  return ax?.response?.data?.message || ax?.message || fallback;
}

function buildSummaryReport(summary: DailySummary, generatedBy: string): BrandedReport {
  return {
    title: "Daily Treasury Summary",
    fileName: `AsanPay_Daily_Treasury_${summary.date}`,
    meta: [
      { label: "Business date", value: summary.date },
      { label: "Generated on", value: new Date().toLocaleString("en-IN") },
      { label: "Generated by", value: generatedBy },
    ],
    summary: [
      { label: "Statement credits", value: `₹${summary.statementCredits}`, tone: "credit" },
      { label: "Statement debits", value: `₹${summary.statementDebits}`, tone: "debit" },
      {
        label: "Unmatched credits",
        value: String(summary.unmatchedCredits),
        tone: summary.unmatchedCredits ? "debit" : "credit",
      },
      {
        label: "Daily close",
        value: summary.dailyClose.closed ? "Closed" : summary.dailyClose.canClose ? "Ready" : "Open",
      },
    ],
    columns: [
      { label: "#" },
      { label: "Metric" },
      { label: "Value", align: "right" },
    ],
    rows: summary.lines.map((l, i) => [
      { text: String(i + 1), align: "center", tone: "muted" },
      { text: l.label },
      { text: l.value, align: "right" },
    ]),
    footerNote:
      "Bank statement CR/DR is separate from API float In/Out. Closing the day locks each bank's opening and closing balances.",
  };
}

function formatInr(v: string | null | undefined): string {
  if (v == null || v === "") return "—";
  const n = Number(v);
  if (!Number.isFinite(n)) return `₹${v}`;
  return `₹${n.toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

function driftLabel(b: BankDayBalance): { text: string; color: string; bg: string } {
  if (b.status === "locked") return { text: "Locked", color: "#15803D", bg: "#DCFCE7" };
  if (b.status === "missing_statement") return { text: "No statement", color: "#B45309", bg: "#FEF3C7" };
  if (b.status === "drift") {
    const n = Number(b.drift);
    const sign = n > 0 ? "+" : "";
    return {
      text: `Drift ${sign}${formatInr(b.drift)}`,
      color: "#B91C1C",
      bg: "#FEE2E2",
    };
  }
  return { text: "Matched", color: "#15803D", bg: "#DCFCE7" };
}

function downloadSummaryCsv(summary: DailySummary) {
  const esc = (v: string) => `"${v.replace(/"/g, '""')}"`;
  const body = ["Metric,Value", ...summary.lines.map((l) => `${esc(l.label)},${esc(l.value)}`)].join("\n");
  const blob = new Blob([`\uFEFF${body}`], { type: "text/csv;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `AsanPay_Daily_Treasury_${summary.date}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

export function DailyClosePanel() {
  const user = useAuthStore((s) => s.user);
  const [date, setDate] = useState(istToday);
  const [status, setStatus] = useState<DailyCloseStatus | null>(null);
  const [summary, setSummary] = useState<DailySummary | null>(null);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [note, setNote] = useState("");
  const [sendEmail, setSendEmail] = useState("");
  const [sendWa, setSendWa] = useState("");
  const [sending, setSending] = useState(false);

  const load = useCallback(async (d: string) => {
    setLoading(true);
    try {
      const [close, sum] = await Promise.all([
        fetchApi<DailyCloseStatus>("/banking/daily-close", { date: d }),
        fetchApi<DailySummary>("/banking/daily-summary", { date: d }),
      ]);
      setStatus(close);
      setSummary(sum);
    } catch (err) {
      toast.error(errMessage(err, "Could not load daily close checklist"));
      setStatus(null);
      setSummary(null);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load(date);
  }, [date, load]);

  async function sendSummary() {
    setSending(true);
    try {
      const { data } = await api.post<{ success: boolean; message?: string }>("/banking/daily-summary/send", {
        date,
        email: sendEmail.trim() || null,
        whatsapp: sendWa.trim() || null,
      });
      if (!data.success) throw new Error(data.message || "Could not send summary");
      toast.success(data.message || "Summary sent");
    } catch (err) {
      toast.error(errMessage(err, "Could not send the daily summary"));
    } finally {
      setSending(false);
    }
  }

  async function closeDay() {
    setBusy(true);
    try {
      const { data } = await api.post<{ success: boolean; data: DailyCloseStatus; message?: string }>(
        "/banking/daily-close",
        { date, note: note.trim() || null },
      );
      if (!data.success) throw new Error(data.message || "Could not close this day");
      setStatus(data.data);
      setNote("");
      toast.success("Business day closed");
    } catch (err) {
      toast.error(errMessage(err, "Could not close this day"));
    } finally {
      setBusy(false);
    }
  }

  async function reopenDay() {
    setBusy(true);
    try {
      const { data } = await api.post<{ success: boolean; data: DailyCloseStatus; message?: string }>(
        "/banking/daily-close/reopen",
        { date },
      );
      if (!data.success) throw new Error(data.message || "Could not reopen this day");
      setStatus(data.data);
      toast.success("Business day reopened");
    } catch (err) {
      toast.error(errMessage(err, "Could not reopen this day"));
    } finally {
      setBusy(false);
    }
  }

  const doneCount = status?.steps.filter((s) => s.done).length ?? 0;
  const totalSteps = status?.steps.length ?? 4;

  return (
    <div className="space-y-5 p-4 md:p-5">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h2 className="text-base font-bold" style={{ color: B.blue }}>
            Daily close
          </h2>
          <p className="mt-0.5 text-sm" style={{ color: B.muted }}>
            Upload → Reconcile → Resolve → Close. Closing locks each bank&apos;s opening and closing for the day.
          </p>
        </div>
        <label className="block text-sm">
          <span className="mb-1 block text-xs font-medium" style={{ color: B.muted }}>
            Business date
          </span>
          <input
            type="date"
            className="h-11 rounded-xl border px-3 text-sm"
            style={{ borderColor: B.border }}
            value={date}
            onChange={(e) => setDate(e.target.value || istToday())}
          />
        </label>
      </div>

      {loading || !status ? (
        <p className="text-sm" style={{ color: B.muted }}>
          {loading ? "Loading checklist…" : "Checklist unavailable."}
        </p>
      ) : (
        <>
          <div
            className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border px-4 py-3"
            style={{
              borderColor: status.closed ? "#BBF7D0" : B.border,
              background: status.closed ? "#F0FDF4" : "#F8FAFC",
            }}
          >
            <div>
              <p className="text-sm font-bold" style={{ color: status.closed ? "#15803D" : B.blue }}>
                {status.closed ? "Day closed" : `Checklist ${doneCount} of ${totalSteps}`}
              </p>
              <p className="text-xs" style={{ color: B.muted }}>
                {status.closed
                  ? `Closed${status.closedByName ? ` by ${status.closedByName}` : ""}${
                      status.closedAt ? ` · ${new Date(status.closedAt).toLocaleString("en-IN")}` : ""
                    } · Balances locked`
                  : "Closing locks opening/closing per bank. Mid-day drift shows statement vs books until then."}
              </p>
              {status.note ? (
                <p className="mt-1 text-xs" style={{ color: B.muted }}>
                  Note: {status.note}
                </p>
              ) : null}
            </div>
            {status.closed ? (
              <button
                type="button"
                disabled={busy}
                onClick={() => void reopenDay()}
                className="inline-flex items-center gap-1.5 rounded-xl border px-4 py-2 text-sm font-bold disabled:opacity-60"
                style={{ borderColor: "#FCA5A5", color: B.danger }}
              >
                <Unlock size={15} /> Reopen day
              </button>
            ) : null}
          </div>

          <ol className="space-y-3">
            {status.steps.map((step, i) => (
              <li
                key={step.id}
                className="rounded-2xl border bg-white p-4 shadow-[0_1px_2px_rgba(15,23,42,0.04)]"
                style={{ borderColor: step.done ? "#BBF7D0" : B.border }}
              >
                <div className="flex flex-wrap items-start justify-between gap-3">
                  <div className="flex min-w-0 gap-3">
                    <div
                      className="mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-full"
                      style={{
                        background: step.done ? "#DCFCE7" : "#F1F5F9",
                        color: step.done ? "#15803D" : B.muted,
                      }}
                    >
                      {step.done ? <CheckCircle2 size={18} /> : <Circle size={18} />}
                    </div>
                    <div className="min-w-0">
                      <p className="text-sm font-bold" style={{ color: B.blue }}>
                        Step {i + 1}. {step.title}
                      </p>
                      <p className="mt-0.5 text-sm" style={{ color: B.muted }}>
                        {step.detail}
                      </p>
                    </div>
                  </div>
                  {step.href && !status.closed ? (
                    <Link
                      href={step.href}
                      className="rounded-lg px-3 py-1.5 text-xs font-bold text-white"
                      style={{ background: B.badgeGrad }}
                    >
                      Open
                    </Link>
                  ) : null}
                </div>
              </li>
            ))}
          </ol>

          {(status.balances?.length ? status.balances : status.banks).length > 0 ? (
            <div className="rounded-2xl border p-4" style={{ borderColor: B.border }}>
              <p className="mb-1 text-xs font-bold uppercase tracking-wide" style={{ color: B.muted }}>
                Opening / closing · mid-day drift
              </p>
              <p className="mb-3 text-xs" style={{ color: B.muted }}>
                Drift = statement closing − books closing. After close, amounts are frozen until you reopen.
              </p>
              <ul className="space-y-2">
                {(status.balances?.length
                  ? status.balances
                  : status.banks.map((b) => ({
                      bankAccountId: b.id,
                      bankName: b.bankName,
                      last4: b.last4,
                      uploaded: b.uploaded,
                      locked: false,
                      lockedAt: null,
                      statementOpening: null,
                      statementClosing: null,
                      booksOpening: "0.00",
                      booksClosing: "0.00",
                      drift: null,
                      status: b.uploaded ? ("ok" as const) : ("missing_statement" as const),
                    }))
                ).map((b) => {
                  const pill = driftLabel(b);
                  return (
                    <li
                      key={b.bankAccountId}
                      className="rounded-xl border px-3 py-3 text-sm"
                      style={{ borderColor: B.border }}
                    >
                      <div className="flex flex-wrap items-center justify-between gap-2">
                        <span className="font-semibold" style={{ color: B.blue }}>
                          {b.bankName} ••{b.last4}
                        </span>
                        <span
                          className="rounded-full px-2 py-0.5 text-[11px] font-bold"
                          style={{ color: pill.color, background: pill.bg }}
                        >
                          {pill.text}
                        </span>
                      </div>
                      <div className="mt-2 grid gap-1 text-xs sm:grid-cols-2" style={{ color: B.muted }}>
                        <p>
                          Statement open {formatInr(b.statementOpening)} · close{" "}
                          {formatInr(b.statementClosing)}
                        </p>
                        <p>
                          Books open {formatInr(b.booksOpening)} · close {formatInr(b.booksClosing)}
                        </p>
                      </div>
                    </li>
                  );
                })}
              </ul>
            </div>
          ) : null}

          {!status.closed ? (
            <div className="space-y-3 rounded-2xl border p-4" style={{ borderColor: B.border }}>
              <label className="block text-sm">
                <span className="mb-1 block font-medium" style={{ color: B.muted }}>
                  Close note (optional)
                </span>
                <input
                  className="w-full rounded-xl border px-3 py-2.5 text-sm"
                  style={{ borderColor: B.border }}
                  value={note}
                  onChange={(e) => setNote(e.target.value)}
                  placeholder="e.g. All Indian Bank lines cleared"
                  maxLength={500}
                  disabled={!status.canClose || busy}
                />
              </label>
              <button
                type="button"
                disabled={!status.canClose || busy}
                onClick={() => void closeDay()}
                className="inline-flex items-center gap-2 rounded-xl px-5 py-2.5 text-sm font-bold text-white disabled:opacity-50"
                style={{ background: status.canClose ? B.badgeGrad : "#94A3B8" }}
              >
                <Lock size={15} />
                {busy ? "Closing…" : "Close & lock balances"}
              </button>
              {!status.canClose ? (
                <p className="text-xs" style={{ color: B.muted }}>
                  Complete every blocking step above before closing.
                </p>
              ) : (
                <p className="text-xs" style={{ color: B.muted }}>
                  After close, statement import and match changes for this date are blocked until you reopen.
                </p>
              )}
            </div>
          ) : null}

          {summary ? (
            <section className="space-y-3 rounded-2xl border p-4" style={{ borderColor: B.border }}>
              <div>
                <h3 className="text-sm font-bold" style={{ color: B.blue }}>
                  Daily summary export
                </h3>
                <p className="mt-0.5 text-xs" style={{ color: B.muted }}>
                  Bank + agent + API snapshot for {summary.date}. Download or send by email / WhatsApp.
                </p>
              </div>
              <div className="flex flex-wrap gap-2">
                <button
                  type="button"
                  onClick={() => {
                    if (!openBrandedPdf(buildSummaryReport(summary, user?.name || "Admin"))) {
                      toast.error("Allow pop-ups to export PDF");
                    }
                  }}
                  className="inline-flex items-center gap-1.5 rounded-lg border px-3 py-2 text-xs font-bold"
                  style={{ borderColor: B.border, color: B.blue }}
                >
                  <FileText size={14} /> PDF
                </button>
                <button
                  type="button"
                  onClick={() => downloadSummaryCsv(summary)}
                  className="inline-flex items-center gap-1.5 rounded-lg border px-3 py-2 text-xs font-bold"
                  style={{ borderColor: B.border, color: B.blue }}
                >
                  <Download size={14} /> CSV
                </button>
                <button
                  type="button"
                  onClick={() => downloadBrandedExcel(buildSummaryReport(summary, user?.name || "Admin"))}
                  className="inline-flex items-center gap-1.5 rounded-lg border px-3 py-2 text-xs font-bold"
                  style={{ borderColor: B.border, color: B.blue }}
                >
                  <FileSpreadsheet size={14} /> XLS
                </button>
              </div>
              <div className="grid gap-3 sm:grid-cols-2">
                <label className="block text-sm">
                  <span className="mb-1 block text-xs font-medium" style={{ color: B.muted }}>
                    Email
                  </span>
                  <input
                    type="email"
                    className="w-full rounded-xl border px-3 py-2.5 text-sm"
                    style={{ borderColor: B.border }}
                    value={sendEmail}
                    onChange={(e) => setSendEmail(e.target.value)}
                    placeholder="ops@example.com"
                  />
                </label>
                <label className="block text-sm">
                  <span className="mb-1 block text-xs font-medium" style={{ color: B.muted }}>
                    WhatsApp mobile
                  </span>
                  <input
                    inputMode="numeric"
                    className="w-full rounded-xl border px-3 py-2.5 text-sm"
                    style={{ borderColor: B.border }}
                    value={sendWa}
                    onChange={(e) => setSendWa(e.target.value.replace(/\D/g, "").slice(0, 10))}
                    placeholder="10-digit mobile"
                  />
                </label>
              </div>
              <button
                type="button"
                disabled={sending || (!sendEmail.trim() && sendWa.length !== 10)}
                onClick={() => void sendSummary()}
                className="rounded-xl px-4 py-2.5 text-sm font-bold text-white disabled:opacity-50"
                style={{ background: B.badgeGrad }}
              >
                {sending ? "Sending…" : "Send summary"}
              </button>
            </section>
          ) : null}
        </>
      )}
    </div>
  );
}
